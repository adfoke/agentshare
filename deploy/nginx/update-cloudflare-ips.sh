#!/usr/bin/env bash
# Regenerate nginx's real-IP configuration from Cloudflare's published ranges.
#
#   ./update-cloudflare-ips.sh            write /etc/nginx/conf.d/cloudflare-realip.conf
#   ./update-cloudflare-ips.sh --check    only report whether anything changed
#
# Why this exists: with Cloudflare in front, every request reaches the origin
# from a Cloudflare address, so nginx would log a Cloudflare IP for every client
# and agentshare's access log would be useless. The realip module reads
# CF-Connecting-IP instead — but only from the ranges listed here.
#
# Cloudflare's lists are stable, but if the site suddenly starts answering with
# the wrong client IPs — or a 522 appears — the first thing to re-run is this.
set -euo pipefail

DEST="/etc/nginx/conf.d/cloudflare-realip.conf"
CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

V4_URL="https://www.cloudflare.com/ips-v4"
V6_URL="https://www.cloudflare.com/ips-v6"
TIMEOUT=20

tmp="$(mktemp)"
ranges="$(mktemp)"
trap 'rm -f "$tmp" "$ranges"' EXIT

# Each list is fetched into its own file, and only then concatenated. Piping
# both through one stream looks tidier and is wrong: Cloudflare's ips-v4 has no
# trailing newline, so the last IPv4 range and the first IPv6 range arrive glued
# together as "131.0.72.0/222400:cb00::/32". nginx rejects that with "host not
# found in set_real_ip_from", and because the bad value is a plausible-looking
# string it reads like a DNS problem rather than a missing newline.
for pair in "v4:$V4_URL" "v6:$V6_URL"; do
    name="${pair%%:*}"
    url="${pair#*:}"
    if ! curl -fsS --max-time "$TIMEOUT" "$url" > "$ranges.$name"; then
        echo "could not fetch $url" >&2
        exit 1
    fi
done
printf '\n' >> "$ranges.v4"   # belt and braces: never rely on the server's
cat "$ranges.v4" "$ranges.v6" | tr -d '\r' | grep -vE '^[[:space:]]*$' \
    | sort -u > "$ranges"
rm -f "$ranges.v4" "$ranges.v6"

# Validate every line as a strict CIDR before anything is written. Without this
# the first sign of a malformed range is `nginx -t` failing — after the bad file
# is already installed, which leaves nginx unable to reload until someone
# notices.
count=$(python3 - "$ranges" <<'PY'
import ipaddress, sys
ok = 0
bad = []
for line in open(sys.argv[1]):
    r = line.strip()
    if not r:
        continue
    try:
        # strict=True rejects an address with bits set outside its prefix, which
        # is the shape a concatenation bug produces.
        ipaddress.ip_network(r, strict=True)
    except ValueError as exc:
        bad.append(f"{r!r}: {exc}")
        continue
    ok += 1
if bad:
    for b in bad:
        print(f"  not a valid CIDR: {b}", file=sys.stderr)
    sys.exit(1)
print(ok)
PY
) || { echo "refusing to install: Cloudflare's lists did not validate" >&2; exit 1; }

if [ "$count" -lt 10 ]; then
    echo "refusing to install: only $count ranges, that cannot be right" >&2
    exit 1
fi

{
    echo "# Generated by update-cloudflare-ips.sh — do not edit by hand."
    echo "# Source: $V4_URL and $V6_URL"
    echo "# Regenerate when client IPs look wrong; see deploy/README.md."
    echo
    sed 's/^/set_real_ip_from /; s/$/;/' "$ranges"
    echo
    # Cloudflare sets this to the original client address on every request.
    echo "real_ip_header CF-Connecting-IP;"
    # Only trust the header from the ranges above; anything else keeps its own
    # peer address.
    echo "real_ip_recursive off;"
} > "$tmp"

if [ "$CHECK" = "1" ]; then
    if [ -f "$DEST" ] && cmp -s "$tmp" "$DEST"; then
        echo "unchanged ($count ranges)"
    else
        echo "differs ($count ranges fetched)"
    fi
    exit 0
fi

install -m 0644 "$tmp" "$DEST"
echo "wrote $DEST ($count ranges)"
nginx -t && systemctl reload nginx
